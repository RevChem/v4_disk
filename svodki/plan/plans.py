def _parse_history_day(raw) -> date | None:
    if not raw:
        return None
    try:
        return date.fromisoformat(str(raw)[:10])
    except ValueError:
        return None


_RAPE_CROPS = frozenset({"Рапс яровой", "Рапс озимый"})
# Озимые культуры посева season year_next без обязательного sowing_date в history.
_OZIMY_SEEDING_OVERLAY_CROPS = frozenset({"Пшеница озимая", "Тритикале озимая"})


def _is_winter_rape_or_wheat(name: str) -> bool:
    """
    Устойчивое распознавание озимых рапса / пшеницы / тритикале независимо от
    точного написания в справочнике культур (полное имя, сокращение «оз»,
    регистр, «ё»/«е»). Не путать с яровыми той же культуры.
    """
    n = str(name or "").strip().lower().replace("ё", "е")
    if not n:
        return False
    if "рапс" not in n and "пшениц" not in n and "тритикал" not in n:
        return False
    return "оз" in n and "яр" not in n


def _is_seeding_other_crop(name: str) -> bool:
    """Культуры строки «Иные» для озимого посева следующего сезона."""
    n = str(name or "").strip().lower().replace("ё", "е")
    if not n:
        return False
    if "введение в оборот" in n:
        return True
    if "многолетние" in n:
        return True
    return n == "пар" or n.startswith("пар ")


def build_field_to_crop(
    *,
    crop_map: dict,
    history_items: list[dict],
    report_date: date,
    period_start: date,
    skip_crops: set | frozenset | None = None,
    season_year: int | None = None,
) -> dict[int, str]:
    """
    Культура поля для посева:
    1) sowing_date в [period_start, report_date] (если несколько — рапс);
    2) добор пустых полей из года отчёта, затем из года+1 (без затирания)
       — пропускается, если задан season_year (озимый сев только сезона year_next);
    3) рапс озимый — если поле не засеяно в периоде (только сезон year_next);
    4) «Пшеница озимая» без sowing_date в периоде убирается — кроме режима
       season_year: тогда пшеница/тритикале берутся из history season year_next
       (как озимый рапс в п.3, sowing_date в API часто пустой).
       Неактивные записи «Рапс озимый» с sowing_date в периоде тоже учитываются
       (в API часто active=False до закрытия сезона).
       «Рапс яровой» season year_next — из history без sowing_date (п.2).

    season_year: если задан (например 2027 для отчёта за 2026), озимный оверлей
    (п.2–4) строится только из history year_next; записи year_now при этом
    всё равно участвуют в п.1 по sowing_date — иначе яровой посев текущего
    года (подсолнечник, соя, пшеница яровая и т.д.) теряется, и факт уходит
    в «Рапс озимый» по оверлею п.3.
    """
    skip = set(skip_crops or ())
    year_now = int(report_date.year)
    year_next = int(season_year) if season_year is not None else year_now + 1
    ozimy_seeding_only = season_year is not None

    def _crop_name(hi: dict) -> tuple[int, str] | None:
        fid, cid = hi.get("field_id"), hi.get("crop_id")
        if not fid or not cid:
            return None
        try:
            fid_i = int(fid)
            cid_i = int(cid)
        except (TypeError, ValueError):
            return None
        name = str(crop_map.get(cid_i) or crop_map.get(cid) or "").strip()
        if not name or name in skip:
            return None
        return fid_i, name

    by_year: dict[int, dict[int, str]] = {}
    sown_by_field: dict[int, list[tuple[date, str]]] = {}
    ww_sown_fields: set[int] = set()
    winter_rape_fields: set[int] = set()
    _winter_excluded = 0
    _winter_kept = 0

    for hi in history_items or []:
        parsed = _crop_name(hi)
        if parsed is None:
            continue
        fid_i, name = parsed
        sd = _parse_history_day(hi.get("sowing_date"))
        sd_in_period = sd is not None and period_start <= sd <= report_date
        try:
            yr = int(hi.get("year") or 0)
        except (TypeError, ValueError):
            yr = 0

        # Яровой/фактический посев текущего года — только по sowing_date (п.1).
        if ozimy_seeding_only and yr == year_now:
            if sd_in_period:
                sown_by_field.setdefault(fid_i, []).append((sd, name))
                if name == "Пшеница озимая":
                    ww_sown_fields.add(fid_i)
            continue

        if not hi.get("active"):
            keep_inactive = (
                ozimy_seeding_only
                and (
                    (name == "Рапс озимый" and sd_in_period)
                    or (yr == year_next and name in _OZIMY_SEEDING_OVERLAY_CROPS)
                )
            )
            if not keep_inactive:
                continue
        if ozimy_seeding_only and yr != year_next:
            continue
        if _is_winter_rape_or_wheat(name):
            if yr != year_next:
                _winter_excluded += 1
                continue
            _winter_kept += 1
        by_year.setdefault(yr, {})[fid_i] = name
        if name == "Рапс озимый":
            winter_rape_fields.add(fid_i)
        if not sd_in_period:
            continue
        sown_by_field.setdefault(fid_i, []).append((sd, name))
        if name == "Пшеница озимая":
            ww_sown_fields.add(fid_i)

    # 1) факт сева по sowing_date
    field_to_crop: dict[int, str] = {}
    for fid_i, items in sown_by_field.items():
        rape = [it for it in items if it[1] in _RAPE_CROPS]
        pool = rape or items
        pool.sort(key=lambda it: it[0], reverse=True)
        field_to_crop[fid_i] = pool[0][1]

    # 2) добор из year_next: «Иные» и яровой рапс без sowing_date в периоде.
    if ozimy_seeding_only:
        for fid_i, name in by_year.get(year_next, {}).items():
            if fid_i not in field_to_crop and (
                _is_seeding_other_crop(name) or name == "Рапс яровой"
            ):
                field_to_crop[fid_i] = name
    else:
        for crop_year in (year_now, year_next, *sorted(
            (y for y in by_year if y not in (year_now, year_next)), reverse=True
        )):
            for fid_i, name in by_year.get(crop_year, {}).items():
                if fid_i not in field_to_crop:
                    field_to_crop[fid_i] = name

    # 3) озимый рапс (только сезон year_next). В режиме ozimy_seeding_only
    # перекрывает яровой факт year_now (sowing_date) — задания season=year_next
    # относятся к озимому севу, а не к прошлому яровому на том же поле.
    for fid_i in winter_rape_fields:
        if ozimy_seeding_only or fid_i not in sown_by_field:
            field_to_crop[fid_i] = "Рапс озимый"

    # 4) озимая пшеница/тритикале — см. docstring (season_year vs sowing_date).
    if ozimy_seeding_only:
        for fid_i, name in by_year.get(year_next, {}).items():
            if name in _OZIMY_SEEDING_OVERLAY_CROPS:
                field_to_crop[fid_i] = name
    else:
        for fid_i, name in list(field_to_crop.items()):
            if name == "Пшеница озимая" and fid_i not in ww_sown_fields:
                del field_to_crop[fid_i]

    print(
        f"    [озимые рапс/пшеница] исключено записей за {year_now}: "
        f"{_winter_excluded}, учтено за {year_next}: {_winter_kept}"
    )
    return field_to_crop


def build_field_to_crop_general(
    *,
    crop_map: dict,
    history_by_year: dict[int, list[dict]],
    priority_year: int,
    skip_crops: set | frozenset | None = None,
    newest_year_wins: bool = False,
) -> dict[int, str]:
    """
    Общая мапа культур (МУ / опрыскивание / уборка): сумма лет history.
    Сначала год отчёта (priority_year-1 при сезоне priority_year), затем остальные,
    без затирания уже заполненных полей — чтобы mid-сезон 26-го не пропадал из‑за планов 27-го.

    Исключение: «Рапс озимый» и «Пшеница озимая» относятся к сезону priority_year
    (например 2027) — записи history_items этих культур за priority_year-1
    (например 2026) полностью игнорируются.

    newest_year_wins: для внесения МУ. Задание сезона 2027 ссылается на history
    этого года (пшеница / соя / картофель). Активный «Рапс яровой» за 2026 на том
    же поле — прошлая культура и не должен оставаться из‑за запрета затирания.
    Годы идут по возрастанию, более новый заменяет более старый.
    """
    skip = set(skip_crops or ())
    field_to_crop: dict[int, str] = {}
    years = sorted(history_by_year.keys())
    if not newest_year_wins:
        # Если передан сезон (year+1) — сначала календарный год отчёта, потом сезон.
        if priority_year in years and (priority_year - 1) in years:
            years = [priority_year - 1, priority_year, *[y for y in years if y not in (priority_year - 1, priority_year)]]
    _winter_excluded = 0
    _winter_kept = 0
    for crop_year in years:
        for hi in history_by_year.get(crop_year, []) or []:
            if not hi.get("active"):
                continue
            fid, cid = hi.get("field_id"), hi.get("crop_id")
            if not fid or not cid:
                continue
            try:
                fid_i = int(fid)
                cid_i = int(cid)
            except (TypeError, ValueError):
                continue
            name = str(crop_map.get(cid_i) or crop_map.get(cid) or "").strip()
            if not name or name in skip:
                continue
            if (
                not newest_year_wins
                and _is_winter_rape_or_wheat(name)
                and crop_year != priority_year
            ):
                _winter_excluded += 1
                continue
            if _is_winter_rape_or_wheat(name):
                _winter_kept += 1
            if fid_i in field_to_crop and not newest_year_wins:
                continue
            field_to_crop[fid_i] = name
    print(
        f"    [озимые рапс/пшеница] исключено записей за {priority_year - 1}: "
        f"{_winter_excluded}, учтено за {priority_year}: {_winter_kept}"
        + (" (для МУ побеждает более новый год history)" if newest_year_wins else "")
    )
    return field_to_crop


def crop_for_disk_field(crops_by_year: dict[int, str], season_year: int | None) -> str:
    """
    Культура дискования — history сезона задания.

    «Зябь» в этом сезоне не считается культурой дискования: если в другом
    сезоне на поле есть настоящая культура, берётся она.
    """
    years = {int(y): str(name or "").strip() for y, name in (crops_by_year or {}).items()}
    if season_year is not None:
        named = years.get(int(season_year), "")
        if named and named != "Зябь":
            return named
    for year in sorted(years, reverse=True):
        named = years[year]
        if named and named != "Зябь":
            return named
    return ""


