class ClassifierEntry:
    __slots__ = ("event", "description", "reason", "factor", "downtime_type")

    def __init__(self, event: str, description: str, reason: str, factor: str, downtime_type: str):
        self.event = event
        self.description = description
        self.reason = reason
        self.factor = factor
        self.downtime_type = downtime_type

    def to_dict(self) -> dict:
        return {
            "event": self.event,
            "description": self.description,
            "reason": self.reason,
            "factor": self.factor,
            "downtimeType": self.downtime_type,
        }


ENTRIES: list[ClassifierEntry] = [ClassifierEntry(*row) for row in _ROWS]

# Быстрый lookup по точной паре (event, description) — для авто-подстановки.
_BY_PAIR: dict[tuple[str, str], ClassifierEntry] = {
    (e.event, e.description): e for e in ENTRIES
}

# Событие -> список его описаний (сохраняем порядок появления в справочнике).
_DESCRIPTIONS_BY_EVENT: dict[str, list[ClassifierEntry]] = {}
for _e in ENTRIES:
    _DESCRIPTIONS_BY_EVENT.setdefault(_e.event, []).append(_e)

# Уникальные события в порядке первого появления — основа для верхнего
# уровня комбобокса.
EVENTS: list[str] = list(_DESCRIPTIONS_BY_EVENT.keys())


def find_classification(event: str, description: str) -> dict | None:
    """Точный поиск по паре (событие, описание). Возвращает reason/factor/type или None."""
    entry = _BY_PAIR.get((event, description))
    return entry.to_dict() if entry else None


def search_events(query: str = "", limit: int = 50) -> list[str]:
    """Список уникальных событий, отфильтрованных по подстроке (регистронезависимо)."""
    q = query.strip().lower()
    if not q:
        return EVENTS[:limit]
    return [ev for ev in EVENTS if q in ev.lower()][:limit]


def get_descriptions(event: str, query: str = "", limit: int = 50) -> list[dict]:
    """Описания для конкретного события (с их reason/factor/type), отфильтрованные по подстроке."""
    entries = _DESCRIPTIONS_BY_EVENT.get(event, [])
    q = query.strip().lower()
    if q:
        entries = [e for e in entries if q in e.description.lower()]
    return [e.to_dict() for e in entries[:limit]]


def search_all(query: str, limit: int = 50) -> list[dict]:
    """
    Плоский поиск по event+description сразу по всему справочнику — для поля
    быстрого поиска "по причинам, описанию" на вкладке "Простои ЗСК".
    """
    q = query.strip().lower()
    if not q:
        return [e.to_dict() for e in ENTRIES[:limit]]
    out = []
    for e in ENTRIES:
        if q in e.event.lower() or q in e.description.lower():
            out.append(e.to_dict())
            if len(out) >= limit:
                break
    return out


def get_domains() -> dict:
    """
    Уникальные значения причины/фактора/типа простоя — для подсказок
    (datalist) в режиме ручного ввода ("Свой вариант"), где эти три поля
    редактируются свободным текстом, но чаще всего совпадают с одним из
    уже существующих в классификаторе значений.
    """
    reasons = sorted({e.reason for e in ENTRIES})
    factors = sorted({e.factor for e in ENTRIES})
    types = sorted({e.downtime_type for e in ENTRIES})
    return {"reasons": reasons, "factors": factors, "downtimeTypes": types}
